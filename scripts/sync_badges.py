#!/usr/bin/env python3
"""Regenerate the badge block and repoint the site links in README.md.

Markdown is static, so a README cannot ask GitHub who its owner is. This
script is the workaround: everything between the `badges-start` and
`badges-end` markers in README.md is generated from the environment, and
the "Sync README badges" workflow runs it on every push to the default
branch and commits the result. Because the generation is idempotent (the
upstream regenerates exactly its own badges), the upstream repository
never sees a commit from this script, while every fork gets one commit
that points its badges at the fork.

The script also rewrites the GitHub Pages URLs of the deployed web
frontend and documentation (the site itself, the config generator, the
current docs and the getting-started guide) to this repository's own
Pages coordinates, and the Docker Hub link in the README to this
repository's own namespace, so a fork's README never sends its readers
to the upstream UI or image page -- and a renamed repository heals its
own links on the next push. The Pages and Docker Hub links are matched
case-insensitively: GitHub keeps the repository's display name in
``GITHUB_REPOSITORY`` while the URLs in the README may carry any
lowercase or mixed-case spelling left over from before a rename.

The web frontend in vulquantafs-gh-pages is not touched: it derives its Docker
image names and Pages links from GITHUB_REPOSITORY and DOCKERHUB_NAMESPACE
when it is built (see vulquantafs-gh-pages/next.config.ts), so no source file
has to be rewritten.

Run it by hand with the environment unset to regenerate the upstream
badges, e.g. after editing the badge layout: the defaults below are the
upstream's coordinates.

Environment:
    GITHUB_REPOSITORY  <owner>/<repo>; defaults to the upstream.
    DEFAULT_BRANCH     the branch the status badges query; defaults to
                       the upstream's default branch, `master`.
    DOCKERHUB_NAMESPACE
                       Docker Hub namespace for the Docker badge link;
                       defaults to the GitHub owner, like the workflows.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

README = Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- badges-start -->"
END = "<!-- badges-end -->"

UPSTREAM_REPOSITORY = "Xyvran/vulquantafs"


def _canonical_pages_site(repository: str) -> str:
    owner, repo_name = repository.split("/", 1)
    # GitHub Pages serves under lowercase owner and repository names;
    # next.config.ts derives its links the same way.
    return "https://{}.github.io/{}".format(owner.lower(), repo_name.lower())


def sync_text(
    text: str, repository: str, branch: str, dockerhub_namespace: str = ""
) -> str:
    """Rewrite ``text`` to point at ``repository``; returns the README text."""
    owner, repo_name = repository.split("/", 1)
    # Docker Hub namespaces are lowercase; a GitHub owner may not be.
    namespace = (dockerhub_namespace or owner).lower()

    pages_site = _canonical_pages_site(repository)
    # Any Pages URL for this repository -- the upstream's, this fork's, or a
    # stale one left behind by a rename or by an all-lowercase writing --
    # is normalized to the current coordinates. Case-insensitive, because
    # GITHUB_REPOSITORY carries the display name (``VulquantaFS``) while
    # the links may spell the same repository ``vulquantafs``.
    pages_link = re.compile(
        r"https://[A-Za-z0-9-]+\.github\.io/" + re.escape(repo_name) + r"(?![\w-])",
        re.IGNORECASE,
    )
    # The Docker Hub URL in the README. Like the Pages links it is written
    # by hand, so any namespace it carries -- the upstream's, a fork's own
    # or a stale one -- is normalized to this repository's own.
    dockerhub_link = re.compile(
        r"https://hub\.docker\.com/r/[A-Za-z0-9-]+/vulquantafs(?![\w-])",
        re.IGNORECASE,
    )
    dockerhub_site = f"https://hub.docker.com/r/{namespace}/vulquantafs"

    block = f"""{START}
<!-- Everything between the markers is generated by scripts/sync_badges.py,
     which the "Sync README badges" workflow runs on every push. Edit the
     script, not this block. -->
[![Tests](https://img.shields.io/github/actions/workflow/status/{repository}/test.yml?branch={branch}&style=for-the-badge&label=tests)](https://github.com/{repository}/actions/workflows/test.yml)
[![Docker build](https://img.shields.io/github/actions/workflow/status/{repository}/docker-publish.yml?branch={branch}&style=for-the-badge&label=docker%20build)](https://github.com/{repository}/actions/workflows/docker-publish.yml)
[![Docker](https://img.shields.io/badge/docker-%230db7ed.svg?style=for-the-badge&logo=docker&logoColor=white)](https://hub.docker.com/r/{namespace}/vulquantafs)
{END}"""
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"the {START} / {END} markers were not found")
    text = pattern.sub(block, text, count=1)
    text = pages_link.sub(pages_site, text)
    return dockerhub_link.sub(dockerhub_site, text)


def main() -> None:
    repository = os.environ.get("GITHUB_REPOSITORY", UPSTREAM_REPOSITORY)
    branch = os.environ.get("DEFAULT_BRANCH", "master")
    namespace = os.environ.get("DOCKERHUB_NAMESPACE", "")
    dockerhub = namespace or repository.split("/")[0].lower()
    text = README.read_text(encoding="utf-8")
    try:
        text = sync_text(text, repository, branch, namespace)
    except ValueError as ex:
        sys.exit(f"{README}: {ex}")
    README.write_text(text, encoding="utf-8")
    sys.stdout.write(
        f"Badges now point at {repository} (branch {branch}, Docker Hub "
        f"{dockerhub}), site links at {_canonical_pages_site(repository)}\n"
    )


if __name__ == "__main__":
    main()
