#!/usr/bin/env python3
"""Regenerate the badge block and repoint the site links in README.md.

Markdown is static, so a README cannot ask GitHub who its owner is. This
script is the workaround: everything between the `badges-start` and
`badges-end` markers in README.md is generated from the environment, and
the "Sync README badges" workflow runs it on every push to the default
branch and commits the result. Because the generation is idempotent (the
upstream regenerates exactly its own badges), the upstream repository
never sees a commit from this script, while every fork gets one commit
that points its badges at the fork.

The script also rewrites the GitHub Pages URLs of the deployed web
frontend (the site itself, the config generator and the getting-started
guide) from the upstream Pages site to the fork's own, so a fork's README
never sends its readers to the upstream UI.

Run it by hand with the environment unset to regenerate the upstream
badges, e.g. after editing the badge layout: the defaults below are the
upstream's coordinates.

Environment:
    GITHUB_REPOSITORY  <owner>/<repo>; defaults to the upstream.
    DEFAULT_BRANCH     the branch the status badges query; defaults to
                       the upstream's default branch, `master`.
    DOCKERHUB_NAMESPACE
                       Docker Hub namespace for the Docker badge link;
                       defaults to the GitHub owner, like the workflows.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

README = Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- badges-start -->"
END = "<!-- badges-end -->"

REPOSITORY = os.environ.get("GITHUB_REPOSITORY", "Xyvran/tgdcfs")
BRANCH = os.environ.get("DEFAULT_BRANCH", "master")
# Docker Hub namespaces are lowercase; a GitHub owner may not be.
NAMESPACE = (
    os.environ.get("DOCKERHUB_NAMESPACE") or REPOSITORY.split("/", 1)[0]
).lower()

UPSTREAM_PAGES = "https://xyvran.github.io/tgdcfs"
# GitHub Pages serves under lowercase owner and repository names.
PAGES_SITE = "https://{}.github.io/{}".format(
    *[part.lower() for part in REPOSITORY.split("/", 1)]
)

BLOCK = f"""{START}
<!-- Everything between the markers is generated by scripts/sync_badges.py,
     which the "Sync README badges" workflow runs on every push. Edit the
     script, not this block. -->
[![Tests](https://img.shields.io/github/actions/workflow/status/{REPOSITORY}/test.yml?branch={BRANCH}&style=for-the-badge&label=tests)](https://github.com/{REPOSITORY}/actions/workflows/test.yml)
[![Docker build](https://img.shields.io/github/actions/workflow/status/{REPOSITORY}/docker-publish.yml?branch={BRANCH}&style=for-the-badge&label=docker%20build)](https://github.com/{REPOSITORY}/actions/workflows/docker-publish.yml)
[![Docker](https://img.shields.io/badge/docker-%230db7ed.svg?style=for-the-badge&logo=docker&logoColor=white)](https://hub.docker.com/r/{NAMESPACE}/tgdcfs)
{END}"""


def main() -> None:
    text = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        sys.exit(f"{README}: the {START} / {END} markers were not found")
    text = pattern.sub(BLOCK, text, count=1)
    text = text.replace(UPSTREAM_PAGES, PAGES_SITE)
    README.write_text(text, encoding="utf-8")
    sys.stdout.write(
        f"Badges now point at {REPOSITORY} (branch {BRANCH}, Docker Hub {NAMESPACE}), "
        f"site links at {PAGES_SITE}\n"
    )


if __name__ == "__main__":
    main()
